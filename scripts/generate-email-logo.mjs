/**
 * Renders public/logo.svg (white KLEACORE wordmark) to the PNG used in
 * e-mails: public/email/logo.png (2x, for an optional hosted copy) and the
 * base64 inline CID attachment in src/lib/notifications/logo.ts. Remote SVG
 * logos do not render in Gmail/Outlook, so mails always carry this PNG.
 *
 *   node scripts/generate-email-logo.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const DISPLAY_WIDTH = 144;
const SCALE = 2;

const svg = await readFile(path.join(root, "public/logo.svg"));
const png = await sharp(svg, { density: 300 })
  .resize({ width: DISPLAY_WIDTH * SCALE })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();
const { width, height } = await sharp(png).metadata();

await writeFile(path.join(root, "public/email/logo.png"), png);
await writeFile(
  path.join(root, "src/lib/notifications/logo.ts"),
  `// Generated by scripts/generate-email-logo.mjs from public/logo.svg — do not edit.
// KLEACORE wordmark (white, ${SCALE}x PNG). Embedded as an inline CID attachment
// so emails never load remote images (no tracking, works offline).
export const LOGO_PNG_BASE64 =
  "${png.toString("base64")}";
export const LOGO_WIDTH = ${DISPLAY_WIDTH};
export const LOGO_HEIGHT = ${Math.round(height / SCALE)};
`
);
console.log(`logo.png ${width}x${height}, ${png.length} bytes`);
